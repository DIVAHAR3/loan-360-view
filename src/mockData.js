export function searchLoans({ customerId, branchCode, loanAccount }) {
  const c = customerId.trim().toLowerCase()
  const b = branchCode.trim().toLowerCase()
  const l = loanAccount.trim().toLowerCase()

  if (!c && !b && !l) return []

  return loans.filter((loan) => {
    const matchesCustomer = c ? loan.customerId.toLowerCase().includes(c) : true
    const matchesBranch = b ? loan.branchCode.toLowerCase().includes(b) : true
    const matchesAccount = l ? loan.loanAccount.toLowerCase().includes(l) : true
    return matchesCustomer && matchesBranch && matchesAccount
  })
}

export function getTotalOutstanding(loan) {
  return loan.components.interest.outstanding + loan.components.principal.outstanding + loan.components.processingFee.outstanding
}
